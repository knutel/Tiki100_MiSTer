"""Build the drive sound ROM from MAME's 5.25" floppy sound samples.

The samples are MAME's default 5.25" drive sounds (samples/floppy/525_*.wav
in the MAME source tree, also installed by Debian's mame-data package in
/usr/share/games/mame/samples/floppy). MAME's samples/README.md puts them
under CC0 1.0 Universal.

The script resamples them from 44.1 kHz to 25 kHz, scales them all by the
same factor to 10-bit signed values and writes:

  rtl/tiki100_drive_sound.hex   the ROM for $readmemh, one sample per line
  rtl/tiki100_drive_sound.svh   start address and length of each sample

Usage: python3 tools/make_drive_sound_rom.py [MAME_SAMPLES_FLOPPY_DIR]
Needs numpy and scipy.
"""

import os
import sys

import numpy as np
import scipy.io.wavfile as wavfile
import scipy.signal as signal

RATE = 25000
PEAK = 480          # the loudest sample peak, of the 10-bit range's 511

# The samples MAME's samples/floppy.xml lists for its default 5.25" drive
# (525_seek_2ms is only used for 3.5" drives). Order = ROM order.
SAMPLES = [
    ("SPIN_START_EMPTY",  "525_spin_start_empty"),
    ("SPIN_START_LOADED", "525_spin_start_loaded"),
    ("SPIN_EMPTY",        "525_spin_empty"),
    ("SPIN_LOADED",       "525_spin_loaded"),
    ("SPIN_END",          "525_spin_end"),
    ("STEP",              "525_step_1_1"),
    ("SEEK_6MS",          "525_seek_6ms"),
    ("SEEK_12MS",         "525_seek_12ms"),
    ("SEEK_20MS",         "525_seek_20ms"),
]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/games/mame/samples/floppy"
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

    data = []
    for name, file in SAMPLES:
        sr, x = wavfile.read(os.path.join(src, file + ".wav"))
        if sr != 44100 or x.ndim != 1:
            sys.exit(f"{file}.wav: expected mono 44.1 kHz")
        data.append(signal.resample_poly(x.astype(float), 250, 441))

    gain = PEAK / max(abs(d).max() for d in data)
    rom = []
    table = []
    for (name, file), d in zip(SAMPLES, data):
        v = np.clip(np.round(d * gain), -511, 511).astype(int)
        table.append((name, file, len(rom), len(v)))
        rom.extend(v.tolist())

    with open(os.path.join(root, "rtl", "tiki100_drive_sound.hex"), "w", newline="\n") as f:
        for v in rom:
            f.write("%03x\n" % (v & 0x3FF))

    with open(os.path.join(root, "rtl", "tiki100_drive_sound.svh"), "w", newline="\n") as f:
        f.write("// Generated by tools/make_drive_sound_rom.py: the samples in\n")
        f.write("// tiki100_drive_sound.hex, 10-bit signed at %d Hz.\n" % RATE)
        f.write("//\n")
        f.write("// Source: MAME's default 5.25\" floppy drive sounds (samples/floppy/ in the\n")
        f.write("// MAME source tree), CC0 1.0 Universal according to MAME's samples/README.md.\n")
        f.write("//\n")
        f.write("// SPDX-License-Identifier: GPL-2.0-or-later\n\n")
        f.write("localparam DS_ROM_SIZE = %d;\n\n" % len(rom))
        for name, file, start, length in table:
            f.write("localparam DS_%-17s = %5d, DS_%s_LEN = %5d;  // %s.wav\n"
                    % (name, start, name, length, file))

    print("%d samples, %.0f ms, gain %.4f" % (len(rom), len(rom) * 1000 / RATE, gain))
    for name, file, start, length in table:
        print("  %-18s %5d %5d  %4.0f ms" % (name, start, length, length * 1000 / RATE))


if __name__ == "__main__":
    main()
